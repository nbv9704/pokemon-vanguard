import {mkdir,readFile,readdir,unlink,writeFile} from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {publicV3Catalog} from '../server/v3-catalog.mjs';

const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const outputDir=path.join(root,'public','item-sprites');
const sheetPath=path.join(outputDir,'itemicons-sheet.png');
const modulePath=path.join(root,'public','js','item-sprites.js');
const manifestPath=path.join(root,'docs','item-assets-manifest.json');
const verifyOnly=process.argv.includes('--verify');
const sheetUrl='https://play.pokemonshowdown.com/sprites/itemicons-sheet.png';
const dataUrl='https://raw.githubusercontent.com/smogon/pokemon-showdown/master/data/items.ts';
const pngMagic=Buffer.from([0x89,0x50,0x4e,0x47,0x0d,0x0a,0x1a,0x0a]);
const toId=value=>String(value||'').toLowerCase().replace(/[^a-z0-9]+/g,'');
const isPng=buffer=>buffer.length>24&&buffer.subarray(0,pngMagic.length).equals(pngMagic);
const dimensions=buffer=>({width:buffer.readUInt32BE(16),height:buffer.readUInt32BE(20)});

async function fetchRequired(url,type){
 const response=await fetch(url,{headers:{'user-agent':'AetherChampions asset fetcher'}});
 if(!response.ok)throw new Error(`${type} request failed (${response.status}): ${url}`);
 return type==='item data'?response.text():Buffer.from(await response.arrayBuffer());
}

function spriteMap(source){
 const map=new Map();
 for(const match of source.matchAll(/^\t([a-z0-9]+):\s*\{([\s\S]*?)^\t\},/gm)){
  const sprite=match[2].match(/^\t\tspritenum:\s*(\d+),/m);
  if(sprite)map.set(match[1],Number(sprite[1]));
 }
 return map;
}

function generatedModule(entries){
 const positions=Object.fromEntries(entries.map(entry=>[entry.id,entry.spriteNumber]));
 return `// Generated by scripts/fetch-item-assets.mjs from Pokémon Showdown's item sprite sheet.\nexport const ITEM_SPRITE_SHEET='/item-sprites/itemicons-sheet.png';\nexport const itemSpriteNumbers=Object.freeze(${JSON.stringify(positions,null,2)});\nexport const itemSpriteStyle=id=>{const sprite=itemSpriteNumbers[id];return Number.isInteger(sprite)?\`--item-col:\${sprite%16};--item-row:\${Math.floor(sprite/16)}\`:'';};\n`;
}

async function verify(){
 const expected=publicV3Catalog.items.filter(item=>item.id!=='none');
 const [sheet,moduleSource,manifestSource]=await Promise.all([readFile(sheetPath),readFile(modulePath,'utf8'),readFile(manifestPath,'utf8')]);
 const problems=[];
 if(!isPng(sheet))problems.push('itemicons-sheet.png is not a valid PNG');
 else{const size=dimensions(sheet);if(size.width!==384||size.height!==1152)problems.push(`unexpected sprite-sheet dimensions: ${size.width}x${size.height}`);}
 const manifest=JSON.parse(manifestSource);
 if(manifest.items.length!==expected.length)problems.push(`manifest has ${manifest.items.length} items; expected ${expected.length}`);
 for(const item of expected){
  const entry=manifest.items.find(candidate=>candidate.id===item.id);
  if(!entry)problems.push(`missing manifest entry: ${item.id}`);
  if(!moduleSource.includes(`"${item.id}"`))problems.push(`missing generated sprite mapping: ${item.id}`);
 }
 if(problems.length)throw new Error(`Held-item asset validation failed:\n- ${problems.join('\n- ')}`);
 console.log(`Held-item assets verified: ${expected.length}/${expected.length} entries from one Pokémon Showdown sprite sheet.`);
}

if(verifyOnly){
 await verify();
}else{
 await mkdir(outputDir,{recursive:true});
 const [source,sheet]=await Promise.all([fetchRequired(dataUrl,'item data'),fetchRequired(sheetUrl,'sprite sheet')]);
 if(!isPng(sheet))throw new Error('Downloaded Pokémon Showdown item sprite sheet is not a PNG.');
 const size=dimensions(sheet);
 if(size.width!==384||size.height!==1152)throw new Error(`Unexpected Pokémon Showdown item sprite-sheet dimensions: ${size.width}x${size.height}`);
 const sprites=spriteMap(source),items=publicV3Catalog.items.filter(item=>item.id!=='none');
 const entries=items.map(item=>{const spriteNumber=sprites.get(toId(item.id));if(!Number.isInteger(spriteNumber))throw new Error(`No Pokémon Showdown sprite mapping for ${item.id}`);return {id:item.id,name:item.name,spriteNumber,column:spriteNumber%16,row:Math.floor(spriteNumber/16),source:'pokemon-showdown'};});
 await writeFile(sheetPath,sheet);
 await writeFile(modulePath,generatedModule(entries));
 await writeFile(manifestPath,`${JSON.stringify({schemaVersion:2,generatedAt:new Date().toISOString(),count:entries.length,sheet:{file:'itemicons-sheet.png',width:size.width,height:size.height,cellWidth:24,cellHeight:24,columns:16},sources:{'pokemon-showdown':{label:'Pokémon Showdown item sprite sheet and item data',sheetUrl,dataUrl}},items:entries},null,2)}\n`);
 for(const file of await readdir(outputDir))if(file.endsWith('.png')&&file!=='itemicons-sheet.png')await unlink(path.join(outputDir,file));
 await verify();
}
