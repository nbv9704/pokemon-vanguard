import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

const appRoot=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const MAX_PRODUCTION_LINES=360;
const SKIP_DIRS=new Set(['node_modules','tests','src']); // src is generated by compile-logic.

function walk(dir,out=[]){
 for(const entry of fs.readdirSync(dir,{withFileTypes:true})){
  if(SKIP_DIRS.has(entry.name))continue;
  const full=path.join(dir,entry.name),relative=path.relative(appRoot,full).replaceAll('\\','/');
  if(entry.isDirectory()){
   if(relative==='server/legacy')continue; // Frozen compatibility snapshot.
   walk(full,out);continue;
  }
  if(!/\.(?:mjs|js)$/.test(entry.name))continue;
  const lines=fs.readFileSync(full,'utf8').split(/\r?\n/).length;
  out.push({relative,lines});
 }
 return out;
}

const files=walk(appRoot),oversized=files.filter(file=>file.lines>MAX_PRODUCTION_LINES).sort((a,b)=>b.lines-a.lines);
if(oversized.length){
 console.error(`Source structure gate failed: production modules should stay <= ${MAX_PRODUCTION_LINES} lines unless they are generated/frozen.`);
 for(const file of oversized)console.error(`- ${file.relative}: ${file.lines} lines`);
 process.exit(1);
}
console.log(`source structure OK — ${files.length} production JS/MJS files, max ${Math.max(...files.map(file=>file.lines))}/${MAX_PRODUCTION_LINES} lines`);
